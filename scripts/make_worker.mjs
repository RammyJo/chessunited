/**
 * Builds sites/worker.generated.js — the Cloudflare Worker entrypoint for the
 * static site.
 *
 * The site is plain static files; the Worker exists so that the security and
 * cache headers in dist/_headers are applied on the Workers host as well, and
 * so that a missing URL returns the custom 404 page with a real 404 status.
 *
 * Runs after `astro build` + `postbuild` so it always embeds the CSP hashes
 * generated for the current build.
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const DIST = path.join(ROOT, 'dist');
const OUT = path.join(ROOT, 'sites');

const headersPath = path.join(DIST, '_headers');
if (!existsSync(headersPath)) {
  console.error('make_worker: dist/_headers is missing — run the build first.');
  process.exit(1);
}

/** Parse a Cloudflare _headers file into [{ pattern, headers: [[name, value], ...] }]. */
function parseHeaders(text) {
  const rules = [];
  let current = null;

  for (const raw of text.split(/\r?\n/)) {
    const line = raw.replace(/\s+$/, '');
    if (!line.trim() || line.trimStart().startsWith('#')) continue;

    if (!/^[ \t]/.test(line)) {
      current = { pattern: line.trim(), headers: [] };
      rules.push(current);
      continue;
    }

    const match = line.trim().match(/^([^:]+):\s*(.*)$/);
    if (match && current) current.headers.push([match[1].trim(), match[2].trim()]);
  }

  return rules.filter((rule) => rule.headers.length > 0);
}

const rules = parseHeaders(await readFile(headersPath, 'utf8'));

const worker = `// Generated by scripts/make_worker.mjs — do not edit by hand.
// Serves the prebuilt static site from env.ASSETS with the header rules from
// dist/_headers and the custom 404 page.
const RULES = ${JSON.stringify(rules, null, 2)};

function matches(pattern, pathname) {
  if (pattern === '/*' || pattern === '*') return true;
  if (pattern.endsWith('/*')) {
    const base = pattern.slice(0, -2);
    return pathname === base || pathname.startsWith(rootify(base));
  }
  return pathname === pattern;
}

function rootify(base) {
  return base.endsWith('/') ? base : base + '/';
}

function applyRules(response, pathname) {
  const out = new Headers(response.headers);
  for (const rule of RULES) {
    if (!matches(rule.pattern, pathname)) continue;
    for (const [name, value] of rule.headers) out.set(name, value);
  }
  return out;
}

export default {
  async fetch(request, env) {
    const url = new URL(request.url);
    const response = await env.ASSETS.fetch(request);

    if (response.status === 404) {
      const notFound = await env.ASSETS.fetch(new URL('/404.html', url));
      const headers = applyRules(notFound, url.pathname);
      headers.set('Content-Type', 'text/html; charset=utf-8');
      headers.set('Cache-Control', 'public, max-age=0, must-revalidate');
      return new Response(notFound.body, { status: 404, headers });
    }

    return new Response(response.body, {
      status: response.status,
      statusText: response.statusText,
      headers: applyRules(response, url.pathname),
    });
  },
};
`;

await mkdir(OUT, { recursive: true });
await writeFile(path.join(OUT, 'worker.generated.js'), worker);
console.log(`make_worker: ${rules.length} header rule(s) embedded -> sites/worker.generated.js`);
